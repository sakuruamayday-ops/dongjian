import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

if (process.platform !== 'darwin') throw new Error('Regenerate product icons on macOS; other platforms use checked-in icons.')
const root = resolve(import.meta.dirname, '..')
const assets = join(root, 'assets')
const temporary = mkdtempSync(join(tmpdir(), 'dongjian-icons-'))
const iconset = join(temporary, 'Dongjian.iconset')
mkdirSync(iconset)
execFileSync('swift', [join(import.meta.dirname, 'render-dongjian-icon.swift'), assets, join(assets, 'fonts/NotoSansSC-Variable.ttf')], { stdio: 'inherit' })
const source = join(assets, 'dongjian-app.png')
for (const size of [16, 32, 128, 256, 512]) {
  for (const scale of [1, 2]) {
    execFileSync('sips', ['-z', String(size * scale), String(size * scale), source, '--out', join(iconset, `icon_${size}x${size}${scale === 2 ? '@2x' : ''}.png`)], { stdio: 'ignore' })
  }
}
execFileSync('iconutil', ['-c', 'icns', iconset, '-o', join(root, 'build/icon-dongjian.icns')])
copyFileSync(join(iconset, 'icon_256x256.png'), join(assets, 'dongjian-mark.png'))
const png = readFileSync(join(assets, 'dongjian-mark.png'))
const sizes = [16, 24, 32, 48, 64, 128, 256]
const icoHeader = Buffer.alloc(6 + sizes.length * 16)
icoHeader.writeUInt16LE(1, 2)
icoHeader.writeUInt16LE(sizes.length, 4)
const images = []
let offset = icoHeader.length
for (const [index, size] of sizes.entries()) {
  const path = join(temporary, `windows-${size}.png`)
  execFileSync('sips', ['-z', String(size), String(size), source, '--out', path], { stdio: 'ignore' })
  const bytes = readFileSync(path)
  const entry = 6 + index * 16
  icoHeader.writeUInt8(size === 256 ? 0 : size, entry)
  icoHeader.writeUInt8(size === 256 ? 0 : size, entry + 1)
  icoHeader.writeUInt16LE(1, entry + 4)
  icoHeader.writeUInt16LE(32, entry + 6)
  icoHeader.writeUInt32LE(bytes.length, entry + 8)
  icoHeader.writeUInt32LE(offset, entry + 12)
  images.push(bytes)
  offset += bytes.length
}
writeFileSync(join(root, 'build/icon-dongjian.ico'), Buffer.concat([icoHeader, ...images]))
const modulePath = resolve(root, '../../packages/client/ui-gongchuang-product/src/client/brand-data.ts')
writeFileSync(modulePath, `// Generated by apps/desktop/scripts/build-dongjian-icons.mjs.\nexport const BRAND_MARK_DATA_URL = 'data:image/png;base64,${png.toString('base64')}'\n`)
console.log('Generated Dongjian application, tray, sidebar and installer icons.')
